/// Look up up to 3 core concepts for an individual stock.
pub fn lookup_stock_concepts(code: &str, name: &str) -> Vec<&'static str> {
    let lower_code = code.to_ascii_lowercase();

    // 1. Direct table match
    if let Some((_, concepts)) = STOCK_CONCEPTS_MAP.iter().find(|(c, _)| c.eq_ignore_ascii_case(&lower_code)) {
        return concepts.to_vec();
    }

    // Also strip prefix (e.g. "sz002242" -> "002242")
    let bare_code = if lower_code.starts_with("sh") || lower_code.starts_with("sz") || lower_code.starts_with("bj") {
        &lower_code[2..]
    } else {
        &lower_code
    };
    if let Some((_, concepts)) = STOCK_CONCEPTS_MAP.iter().find(|(c, _)| {
        let bare = if c.starts_with("sh") || c.starts_with("sz") || c.starts_with("bj") {
            &c[2..]
        } else {
            *c
        };
        bare == bare_code
    }) {
        return concepts.to_vec();
    }

    // 2. Dynamic heuristic keywords based on security name
    let mut matched = Vec::new();
    let name_rules: &[(&[&str], &str)] = &[
        (&["文化", "传媒", "影视", "院线", "出版", "广告"], "影视院线"),
        (&["游戏", "互娱", "动漫", "娱乐"], "网络游戏"),
        (&["数字", "数据"], "数字媒体"),
        (&["酒"], "白酒"),
        (&["银行"], "银行"),
        (&["证券", "信托"], "证券"),
        (&["药", "生化"], "医药"),
        (&["芯", "半导体", "微电"], "半导体"),
        (&["光伏", "太阳能"], "光伏设备"),
        (&["锂", "电池"], "电池"),
        (&["车", "汽"], "汽车"),
        (&["电", "能"], "电力"),
        (&["煤"], "煤炭"),
        (&["软件", "信息"], "软件开发"),
        (&["航", "军"], "军工"),
        (&["油", "气"], "油气"),
        (&["金", "铜", "铝"], "有色金属"),
        (&["通", "讯"], "通信设备"),
        (&["家电", "电器"], "家电"),
        (&["建", "路桥", "交建", "基建", "工程"], "基础建设"),
        (&["商", "百货", "超市", "零售", "旅游", "免税"], "商业消费"),
        (&["机械", "机床", "自动化", "重机"], "通用设备"),
        (&["化", "材料", "胶", "塑", "纤"], "化学制品"),
        (&["运", "物流", "港", "海运", "集运", "快递"], "交通运输"),
        (&["农", "粮", "种", "猪", "饲料", "水产", "渔"], "农林牧渔"),
    ];

    for (kws, concept) in name_rules {
        if kws.iter().any(|k| name.contains(k)) && !matched.contains(concept) {
            matched.push(*concept);
            if matched.len() >= 3 {
                break;
            }
        }
    }

    matched
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_lookup_prominent_stocks() {
        let jiu_yang = lookup_stock_concepts("sz002242", "九阳股份");
        assert_eq!(jiu_yang, vec!["小家电", "智能家居", "预制菜"]);

        let byd = lookup_stock_concepts("sz002594", "比亚迪");
        assert_eq!(byd, vec!["乘用车", "新能源车", "锂电池"]);

        let maotai = lookup_stock_concepts("sh600519", "贵州茅台");
        assert_eq!(maotai, vec!["白酒", "消费", "中特估"]);

        let dasheng = lookup_stock_concepts("sh600892", "大晟文化");
        assert_eq!(dasheng, vec!["影视院线", "网络游戏", "文化传媒"]);
    }

    #[test]
    fn test_lookup_heuristic_fallback() {
        let bank = lookup_stock_concepts("sh601998", "中信银行");
        assert!(bank.contains(&"银行"));

        let media = lookup_stock_concepts("sz000000", "未知文化");
        assert!(media.contains(&"影视院线"));

        let _solar = lookup_stock_concepts("sz002056", "横店东磁");
        // Name contains no direct rule, fallback is empty or general
        assert_eq!(lookup_stock_concepts("sz000000", "未知代码"), Vec::<&'static str>::new());
    }
}
